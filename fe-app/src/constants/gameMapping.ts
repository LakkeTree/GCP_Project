/**
 * 게임명을 전달받아 백엔드 API용 target_game 코드로 변환하는 유틸리티 함수
 */
export const getGameCode = (gameTitle: string): string => {
  if (!gameTitle || !gameTitle.trim()) {
    return 'ALL';
  }

  const trimmed = gameTitle.trim();

  // 1. 매핑 테이블 완벽 일치 검사
  if (GAME_CODE_MAP[trimmed]) {
    return GAME_CODE_MAP[trimmed];
  }

  // 2. 괄호, 콜론, 공백 변형 유연 매칭 (예: "Roblox" <-> "Roblox (로블록스)")
  const cleanInput = trimmed.replace(/\([^)]*\)/g, '').replace(/[\s:-]/g, '').toLowerCase();

  const foundKey = Object.keys(GAME_CODE_MAP).find((key) => {
    const cleanKey = key.replace(/\([^)]*\)/g, '').replace(/[\s:-]/g, '').toLowerCase();
    return cleanKey === cleanInput || cleanInput.includes(cleanKey) || cleanKey.includes(cleanInput);
  });

  if (foundKey) {
    return GAME_CODE_MAP[foundKey];
  }

  // 3. 미등록 신규 게임은 기본 공통 혜택 연산용 'ALL' 반환
  return 'ALL';
};